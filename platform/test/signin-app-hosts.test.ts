import fs from 'node:fs';
import { describe, expect, it } from 'vitest';
import { appLabels, expected, labelOf, OUT, render, yamlValue } from '../app-hosts.mjs';
import { DEPLOYED_APP_LABELS } from '../src/signin/app-hosts.ts';

describe('platform/src/signin/app-hosts.ts', () => {
  it('is current: run `npm run app-hosts` in platform/ after adding an app, then redeploy sign-in-link', () => {
    expect(fs.readFileSync(OUT, 'utf8')).toBe(expected());
  });
  it('holds no non-app label', () => {
    expect(DEPLOYED_APP_LABELS).not.toContain('auth');
    expect(DEPLOYED_APP_LABELS.every((l) => /^[a-z0-9-]{1,63}$/.test(l))).toBe(true);
  });
});

describe('the generator', () => {
  const target = (netlify: string) => `provider: netlify\nprojectName: x\nnetlify:\n${netlify}\n`;
  it('reads netlify.customDomain through the domain mapping', () => {
    expect(labelOf(target('  customDomain: pluck-lab.pisan.me'))).toBe('pluck-lab');
    expect(labelOf(target("  customDomain: 'daily-project-ideas.pisan.me' # renamed"))).toBe('studio');
    expect(labelOf(target('  customDomain: x.hintwise.org'))).toBe('x');
    expect(labelOf(target('  customDomain: shop.example.com'))).toBeNull();
    expect(labelOf(target('  customDomain: a.b.pisan.me'))).toBeNull();
  });
  it('falls back to netlify.siteName, and skips a target with neither', () => {
    expect(labelOf(target('  siteName: Fork-Count'))).toBe('fork-count');
    expect(labelOf(target("  siteName: 'bad name'"))).toBeNull();
    expect(labelOf('provider: render\nservice: backend-hub\n')).toBeNull();
  });
  it('reads values without quotes or comments', () => {
    expect(yamlValue('netlify:\n  siteName: "a-b" # note\n', 'siteName')).toBe('a-b');
    expect(yamlValue('siteName: top-level\n', 'siteName')).toBe('');
  });
  it('sorts, dedupes and renders', () => {
    const labels = appLabels([target('  siteName: b'), target('  siteName: a'), target('  customDomain: a.pisan.me'), 'nothing']);
    expect(labels).toEqual(['a', 'b']);
    expect(render(labels)).toBe(
      "// Generated by platform/app-hosts.mjs from */deploy/target.yml: do not edit.\n// After adding an app: `npm run app-hosts` in platform/, commit, then redeploy sign-in-link.\nexport const DEPLOYED_APP_LABELS: readonly string[] = [\n  'a',\n  'b',\n];\n",
    );
  });
});
