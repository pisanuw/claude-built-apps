#!/usr/bin/env node
/**
 * Writes platform/src/signin/app-hosts.ts: the https://<label>.hintwise.org
 * labels of the apps deployed from this repo, read from <app>/deploy/target.yml
 * (netlify.customDomain mapped through scripts/domains.mjs, else
 * netlify.siteName). sign-in-link only sends links back to those apps (plus
 * the few outside this repo listed in src/signin/validate.ts).
 *
 *   node platform/app-hosts.mjs           rewrite the file
 *   node platform/app-hosts.mjs --check   exit 1 when the file is out of date
 *
 * test/signin-app-hosts.test.ts runs the same check in CI. After adding an
 * app, run `npm run app-hosts` in platform/, commit, and redeploy
 * sign-in-link (deploy-function sign-in-link) so the function knows it.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { appDomainFor, APP_DOMAIN } from '../scripts/domains.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const ROOT = path.resolve(HERE, '..');
export const OUT = path.join(HERE, 'src', 'signin', 'app-hosts.ts');

/** Pure: the value of an indented `key: value` line in a target.yml, without quotes and comments. */
export function yamlValue(text, key) {
  const m = String(text).match(new RegExp(`^\\s+${key}:\\s*([^#\\n]*)`, 'm'));
  return m ? m[1].trim().replace(/^['"]|['"]$/g, '') : '';
}

/** Pure: the app's hintwise.org label from its target.yml text, or null. */
export function labelOf(text) {
  const custom = yamlValue(text, 'customDomain');
  if (custom) {
    const host = appDomainFor(custom);
    return host.endsWith(`.${APP_DOMAIN}`) && !host.slice(0, -(APP_DOMAIN.length + 1)).includes('.') ? host.slice(0, -(APP_DOMAIN.length + 1)) : null;
  }
  const site = yamlValue(text, 'siteName').toLowerCase();
  return /^[a-z0-9-]{1,63}$/.test(site) ? site : null;
}

/** Pure: the sorted, unique labels of a set of target.yml texts. */
export function appLabels(texts) {
  return [...new Set(texts.map(labelOf).filter(Boolean))].sort();
}

/** Pure: the generated module. */
export function render(labels) {
  return [
    '// Generated by platform/app-hosts.mjs from */deploy/target.yml: do not edit.',
    '// After adding an app: `npm run app-hosts` in platform/, commit, then redeploy sign-in-link.',
    'export const DEPLOYED_APP_LABELS: readonly string[] = [',
    ...labels.map((l) => `  '${l}',`),
    '];',
    '',
  ].join('\n');
}

/** The target.yml texts of this repo. */
export function readTargets(root = ROOT) {
  return fs
    .readdirSync(root, { withFileTypes: true })
    .filter((e) => e.isDirectory() && !e.name.startsWith('.'))
    .map((e) => path.join(root, e.name, 'deploy', 'target.yml'))
    .filter((f) => fs.existsSync(f))
    .map((f) => fs.readFileSync(f, 'utf8'));
}

/** The file as it should be now. */
export const expected = (root = ROOT) => render(appLabels(readTargets(root)));

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const want = expected();
  const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (process.argv.includes('--check')) {
    if (want !== have) {
      console.log('::error::platform/src/signin/app-hosts.ts is out of date: run `npm run app-hosts` in platform/ and commit it.');
      process.exit(1);
    }
    console.log('platform/src/signin/app-hosts.ts is current.');
  } else {
    fs.writeFileSync(OUT, want);
    console.log(`Wrote ${path.relative(ROOT, OUT)}: ${want.split('\n').filter((l) => l.startsWith("  '")).length} app labels.`);
  }
}
